"""Regenerate docs/data_dictionary.md and docs/database_diagram.md from the SQLAlchemy schema.

Run from the project root:   python scripts/generate_docs.py
Keeping these files generated means the documentation cannot drift away from the code.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from retailiq.db.schema import TABLE_ORDER, metadata  # noqa: E402

GROUPS = {
    "Reference data": ["meta", "stores", "suppliers", "products", "campaigns", "customers"],
    "Sales and collections": ["sales_transactions", "sales_lines", "returns", "opening_receivables", "customer_receipts"],
    "Procurement and stock": ["purchase_orders", "purchase_order_lines", "supplier_invoices", "supplier_payments", "stock_movements", "inventory_daily"],
    "Costs, assets and financing": ["operating_expenses", "capital_expenditures", "loans", "loan_payments", "equity_transactions", "opening_balances", "budgets",
                                    "cash_ledger", "planned_cash_items"],
    "Marketing and feedback": ["campaign_daily", "reviews"],
}


def _fk(t):
    return [f"`{fk.parent.name}` → `{fk.column.table.name}.{fk.column.name}`" for fk in t.foreign_keys]


def dictionary() -> str:
    out = ["# Data dictionary", "",
           "*Generated from `retailiq/db/schema.py` by `scripts/generate_docs.py`. All data is SIMULATED. Money is in INR and excludes GST; dates are stored as ISO text (`YYYY-MM-DD`).*", "",
           "Every table lists its **grain** (what one row represents) and its **keys**. Always aggregate to a common grain before joining two tables.", ""]
    for group, tables in GROUPS.items():
        out += [f"## {group}", ""]
        for name in tables:
            t = metadata.tables[name]
            pk = ", ".join(f"`{c.name}`" for c in t.primary_key.columns)
            out += [f"### `{name}`", "", f"**Grain:** {t.info.get('grain', '')}", "", f"**Primary key:** {pk}"]
            fks = _fk(t)
            if fks:
                out += ["", "**Foreign keys:** " + "; ".join(fks)]
            out += ["", "| Column | Type | Nullable |", "|---|---|---|"]
            for c in t.columns:
                out.append(f"| `{c.name}` | {c.type} | {'yes' if c.nullable else 'no'} |")
            out.append("")
    missing = set(TABLE_ORDER) - {n for ts in GROUPS.values() for n in ts}
    assert not missing, f"tables missing from GROUPS: {missing}"
    return "\n".join(out)


def diagram() -> str:
    out = ["# Database diagram", "",
           "*Generated by `scripts/generate_docs.py`. The same diagram is drawn interactively on the app's \"Data, definitions & checks\" page.*", "",
           "## Entity-relationship diagram (Mermaid)", "",
           "Open this file in VS Code with the *Markdown Preview Mermaid Support* extension, or paste the block into https://mermaid.live.", "", "```mermaid", "erDiagram"]
    for t in metadata.sorted_tables:
        for fk in t.foreign_keys:
            out.append(f"    {fk.column.table.name} ||--o{{ {t.name} : \"{fk.parent.name}\"")
    out += ["```", "", "## Relationships in words", ""]
    for group, tables in GROUPS.items():
        out.append(f"**{group}**")
        for name in tables:
            fks = _fk(metadata.tables[name])
            if fks:
                out.append(f"- `{name}` references: " + "; ".join(fks))
        out.append("")
    out += ["## How the areas connect", "",
            "```",
            "customers ──┐                     ┌── campaigns ── campaign_daily (spend, impressions, clicks)",
            "stores ─────┼── sales_transactions ┤",
            "            │        │             └── (campaign_id: ONE campaign per sale = attribution)",
            "products ───┤   sales_lines ── returns",
            "suppliers ──┘        │",
            "   │                 └── stock_movements ── inventory_daily     (sale lines leave stock at weighted-average cost)",
            "   └── purchase_orders ── purchase_order_lines ── stock_movements (receipts enter stock)",
            "            └── supplier_invoices ── supplier_payments           (payables)",
            "customer_receipts (collections)   operating_expenses   capital_expenditures",
            "loans ── loan_payments (interest / principal)   equity_transactions   opening_balances",
            "          └────────── everything that moves cash is summarised in cash_ledger ──────────┘",
            "reviews ── (customer, product, store, transaction)",
            "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "data_dictionary.md").write_text(dictionary(), encoding="utf-8")
    (docs / "database_diagram.md").write_text(diagram(), encoding="utf-8")
    print("Wrote docs/data_dictionary.md and docs/database_diagram.md")
